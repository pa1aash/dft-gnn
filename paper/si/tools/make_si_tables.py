# ---------------------------------------------------------------- A by GPU class

def gpu_class_table(m: Macros) -> None:
    rows = []
    for rec, block, points in (("precision_a_b400_b654", "precision", ("400", "654")),
                               ("cv_extended_budget", "cv", ("10", "20"))):
        node = json.loads((ROOT / "results" / f"{rec}.json").read_text())["payload"]["descriptive"]["gpu_class"]
        for pt in points:
            first = True
            for it in node[f"{block}|{pt}"]:
                base = (f"results/{rec}.json#/payload/descriptive/gpu_class/{block}|{pt}/"
                        f"{it['backbone']}_{it['gpu_class']}")
                cls = GPU[it["gpu_class"]] + (" (not in N1)" if it["gpu_class"] == "RTX 4090" else "")
                apc = it.get("A_paired_cells") or {}
                if apc.get("A") is not None:
                    a = m(f"{base}/A_paired_cells/A")
                    ci = (r"\ci{" + m(f"{base}/A_paired_cells/ci95_descriptive/item1") + "}{"
                          + m(f"{base}/A_paired_cells/ci95_descriptive/item2") + "}")
                else:
                    a, ci = "--", ""
                runs = []
                for k in ("S", "D"):
                    runs.append(m(f"{base}/n_runs/{k}") if (it.get("n_runs") or {}).get(k) is not None else "--")
                point = budget(m, pt) if block == "precision" else rf"$K = {m(f'{base}/point')}$"
                rows.append(" & ".join([("precision" if block == "precision" else "grouped CV") if first else "",
                                        point if first else "", it["backbone"], cls, " / ".join(runs),
                                        m(f"{base}/n_paired_cells"), a, ci]) + r" \\")
                first = False
            rows.append(r"\addlinespace")
    body = (r"\begin{longtable}{@{}lllllrrl@{}}" "\n"
            r"\caption{The advantage $A$ by GPU class of the training runs (extension, descriptive, no test). "
            r"$A$ is the mean over paired cells (the S and D runs of the same resample or fold, budget and seed, "
            r"both on that class) of the single-run difference MAE$_\mathrm{S}$ $-$ MAE$_\mathrm{D}$ (eV); the "
            r"interval is a descriptive percentile interval of a bootstrap over the cells. Runs: all runs of S and "
            r"of D on that class at that point. ``Original sweep'' holds the registered sweep runs of the original "
            r"resamples and seeds. Records: \recprecision{} and \reccv{}, key "
            r"\texttt{payload.descriptive.gpu\_class}.}"
            r"\label{tab:gpu_class}\\" "\n" r"\toprule" "\n"
            r"Design & Point & Network & GPU class & Runs S / D & Cells & $A$ & Interval \\" "\n" r"\midrule" "\n"
            r"\endfirsthead" "\n" r"\toprule" "\n"
            r"Design & Point & Network & GPU class & Runs S / D & Cells & $A$ & Interval \\" "\n" r"\midrule" "\n"
            r"\endhead" "\n" r"\bottomrule" "\n" r"\endlastfoot" "\n" + "\n".join(rows[:-1]) + "\n"
            r"\end{longtable}" "\n")
    write(SI / "sections" / "tab_gpu_class.tex",
          "results/precision_a_b400_b654.json, results/cv_extended_budget.json (payload.descriptive.gpu_class)", body)


