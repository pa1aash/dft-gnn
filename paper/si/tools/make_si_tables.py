def main() -> int:
    m = Macros(TSV)
    tuned_tables(m)
    capped_table(m)
    n1_table(m)
    gpu_class_table(m)
    withinhost_table(m)
    first_shell_table(m)
    taxonomy_table()
    provenance_table()
    tags_table()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
