# ---------------------------------------------------------------- static tables

CLASS_LABEL = {"host-electronic DFT": "host-electronic", "site-electronic DFT": "site-electronic",
               "structural/compositional": "structural"}


def taxonomy_table() -> None:
    rows = list(csv.DictReader((ROOT / "docs" / "descriptor_taxonomy.csv").open()))
    cls_order = ("host-electronic DFT", "site-electronic DFT", "structural/compositional")
    out = []
    for cls in cls_order:
        group = [r for r in rows if r["class"] == cls]
        fractions = [r for r in group if r["definition"].startswith("Fraction w_")]
        for r in group:
            if r in fractions:
                continue
            units = re.split(r" \(|;", r["units"])[0]
            units = r"\AA$^{3}$" if units == "A^3" else tex_escape(units)
            out.append(" & ".join([r"\texttt{" + tex_escape(r["name"]) + "}", CLASS_LABEL[cls], units,
                                   tex_escape(r["definition"].split(". ")[0].rstrip("."))]) + r" \\")
        if fractions:
            names = ", ".join(r["name"] for r in fractions)
            out.append(r"\texttt{w\_X} & " + CLASS_LABEL[cls] + r" & fraction & Fraction of the solid angle of "
                       r"the O-site Voronoi cell (pristine unit cell) that faces element X, for X in: "
                       + tex_escape(names) + r" \\")
        out.append(r"\addlinespace")
    body = (r"\begin{longtable}{@{}>{\raggedright}p{0.25\linewidth}>{\raggedright}p{0.15\linewidth}"
            r">{\raggedright}p{0.135\linewidth}>{\raggedright\arraybackslash}p{0.385\linewidth}@{}}" "\n"
            r"\caption{The descriptors of the release of Kumagai et al.\ \citep{Kumagai2021insights} and their "
            r"classes, transcribed from \texttt{docs/descriptor\_taxonomy.csv} (names as in the release; definition "
            r"abridged to its first sentence). The host-electronic and site-electronic DFT descriptors are those "
            r"given to D; RF-Kumagai uses all of them, RF-electronic the two electronic classes and RF-structural the "
            r"structural and compositional class. Every descriptor is a property of the pristine host; "
            r"\texttt{formation\_energy} is the formation energy of the host oxide, not the vacancy target.}"
            r"\label{tab:taxonomy}\\" "\n" r"\toprule" "\n" r"Name & Class & Units & Definition \\" "\n"
            r"\midrule" "\n" r"\endfirsthead" "\n" r"\toprule" "\n" r"Name & Class & Units & Definition \\"
            "\n" r"\midrule" "\n" r"\endhead" "\n" r"\bottomrule" "\n" r"\endlastfoot" "\n" + "\n".join(out[:-1])
            + "\n" r"\end{longtable}" "\n")
    write(SI / "tables" / "descriptor_taxonomy.tex", "docs/descriptor_taxonomy.csv", body)


def provenance_table() -> None:
    text = (ROOT / "docs" / "provenance_labels.md").read_text()
    rows = []
    for line in text.splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) == 7 and cells[0].isdigit():
            num, group, _records, backbone, _rule, _first, label = cells
            rows.append(" & ".join([num, md_inline(group), md_inline(backbone), md_inline(label)]) + r" \\")
    if len(rows) != 35:
        sys.exit(f"provenance table: expected 35 groups in docs/provenance_labels.md, found {len(rows)}")
    body = (r"\begin{longtable}{@{}r>{\raggedright}p{0.36\linewidth}>{\raggedright}p{0.2\linewidth}"
            r">{\raggedright\arraybackslash}p{0.3\linewidth}@{}}" "\n"
            r"\caption{Provenance label of every result group, transcribed from \texttt{docs/provenance\_labels.md} "
            r"(groups 1 to 19: the collaborator analysis at its ingest; groups 20 to 35: the analyses added at the "
            r"results freeze). PRE-REGISTERED: the originally registered backbone (v1) with the deciding rule "
            r"committed before the results; POST HOC: the primary backbone (v2), or a rule committed after the "
            r"results it decides; EXTENSION: compute or analysis beyond the registered plan. The labels record "
            r"chronology, not quality. The records, rule commits and first-result times of every group are in the "
            r"same file.}\label{tab:provenance}\\" "\n" r"\toprule" "\n" r"\# & Group & Network & Label \\" "\n"
            r"\midrule" "\n" r"\endfirsthead" "\n" r"\toprule" "\n" r"\# & Group & Network & Label \\" "\n"
            r"\midrule" "\n" r"\endhead" "\n" r"\bottomrule" "\n" r"\endlastfoot" "\n" + "\n".join(rows) + "\n"
            r"\end{longtable}" "\n")
    write(SI / "tables" / "provenance_labels.tex", "docs/provenance_labels.md", body)


