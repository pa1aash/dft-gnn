"""Write the tables of the Supplementary Materials (paper/si).

Two kinds of output:

* paper/si/sections/tab_*.tex: tables of results and protocol values. Every number is a macro of
  paper/generated/numbers.tex, found in paper/generated/numbers.tsv by the JSON pointer of its source (run
  paper/tools/make_numbers.py first). A pointer without a macro is an error. These files are scanned by
  paper/tools/check_macros.py like the SI prose.
* paper/si/tables/*.tex: static text tables copied from repository documents (descriptor names and classes
  from docs/descriptor_taxonomy.csv, provenance labels from docs/provenance_labels.md, release tags). They
  hold identifiers, dates and commits, not results, and are \\input like paper/tables/.

Nothing is computed: values are read from the records through their macros, and the static tables are
transcriptions of the documents named.

Usage: python paper/si/tools/make_si_tables.py
"""

from __future__ import annotations

import csv
import json
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[3]
SI = ROOT / "paper" / "si"
TSV = ROOT / "paper" / "generated" / "numbers.tsv"
ANCHORS = ("50", "200", "654")
PARAMS = ("learning_rate", "weight_decay", "hidden_width", "megnet_blocks", "dropout", "batch_size",
          "readout_mlp_width")
SIG = ("learning_rate", "weight_decay", "dropout")
BUDGETS = ("25", "50", "100", "200", "400", "654")
# GPU class names as text macros of paper/si/sisetup.sty (the names contain digits)
GPU = {"A10": r"\gpushortaten{}", "RTX 3090": r"\gpushortthreeoh{}", "RTX A4000": r"\gpushortafour{}",
       "L4": r"\gpushortlfour{}", "RTX 4090": r"\gpushortfourty{}", "original sweep": "original sweep"}


def budget(m: "Macros", b: str) -> str:
    """Macro of a registered training budget (configs/config.yaml budgets.hosts)."""
    return m(f"configs/config.yaml#/budgets/hosts/item{1 + BUDGETS.index(b)}")


class Macros:
    """JSON pointer (as written in numbers.tsv) -> macro name."""

    def __init__(self, tsv: Path) -> None:
        if not tsv.exists():
            sys.exit(f"missing {tsv}; run paper/tools/make_numbers.py")
        self.by_src: dict[str, str] = {}
        for line in tsv.read_text().splitlines()[1:]:
            name, _latex, _raw, src = line.split("\t")
            self.by_src[src] = name

    def __call__(self, src: str) -> str:
        if src not in self.by_src:
            raise KeyError(f"no macro for {src}")
        return self.by_src[src] + "{}"

    def get(self, src: str) -> str | None:
        return self.by_src[src] + "{}" if src in self.by_src else None


def tex_escape(s: str) -> str:
    rep = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_",
           "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\^{}"}
    s = "".join(rep.get(c, c) for c in s)
    for a, b in (("§", r"\S{}"), ("≤", r"$\leq$"), ("≥", r"$\geq$"), ("×", r"$\times$"), ("−", "-"),
                 ("–", "--"), ("Å", r"\AA{}"), ("μ", r"$\mu$"), ("²", r"$^{2}$"), ("’", "'"), ("→", r"$\to$"), ("Δ", r"$\Delta$"), ("ρ", r"$\rho$")):
        s = s.replace(a, b)
    bad = sorted({c for c in s if ord(c) > 127})
    if bad:
        sys.exit(f"tex_escape: no mapping for {bad}")
    return s


def md_inline(s: str) -> str:
    """Markdown inline code and bold to LaTeX (escaped)."""
    parts = re.split(r"(`[^`]*`)", s)
    out = []
    for p in parts:
        if p.startswith("`") and p.endswith("`"):
            out.append(r"\texttt{" + re.sub(r"(/|\\_)", r"\1\\allowbreak{}", tex_escape(p[1:-1])) + "}")
        else:
            out.append(re.sub(r"\*\*(.+?)\*\*", r"\\textbf{\1}", tex_escape(p)))
    return "".join(out)


HEAD = "% Generated by paper/si/tools/make_si_tables.py from {src}. Do not edit.\n"


def write(path: Path, src: str, body: str) -> None:
    path.write_text(HEAD.format(src=src) + body)
    print(f"wrote {path.relative_to(ROOT)}")


# ---------------------------------------------------------------- tuned values

def tuned_rows(m: Macros, cfg: str, models: list[tuple[str, str]], best: str | None) -> list[str]:
    rows = []
    tuned = yaml.safe_load((ROOT / cfg).read_text())["models"]
    for key, label in models:
        for i, b in enumerate(ANCHORS):
            cells = [label if i == 0 else "", m(f"configs/config.yaml#/tuning/anchors/item{i + 1}")]
            for p in PARAMS:
                src = f"{cfg}#/models/{key}/{b}/{p}"
                cells.append(m(src + " (3 s.f.)") if p in SIG else m(src))
            cells.append(tuned[key][int(b)]["pooling"])
            if best is not None:
                cells.append(m(f"results/tuning_summary.json#/payload/studies/{key}_a{b}/best_value"))
            rows.append(" & ".join(cells) + r" \\")
        rows.append(r"\addlinespace")
    return rows[:-1]


def tuned_tables(m: Macros) -> None:
    head = (r"Model & Anchor & Learning rate & Weight decay & Width & Blocks & Dropout & Batch & Readout & "
            r"Pooling")
    v1 = tuned_rows(m, "configs/tuned_v1.yaml",
                    [("S", "S"), ("D-state", "D (D-state)"), ("D-late", "D-late"), ("P1", "P1")], best="yes")
    body = (r"\begin{tabular}{@{}llllllllllr@{}}" "\n" r"\toprule" "\n" + head +
            r" & Val.\ MAE \\" "\n" r"\midrule" "\n" + "\n".join(v1) + "\n" r"\bottomrule" "\n" r"\end{tabular}" "\n")
    write(SI / "sections" / "tab_tuned_v1.tex", "configs/tuned_v1.yaml, results/tuning_summary.json", body)
    v2 = tuned_rows(m, "configs/tuned_v2.yaml", [("S", "S"), ("D-state", "D (D-state)")], best=None)
    body = (r"\begin{tabular}{@{}llllllllll@{}}" "\n" r"\toprule" "\n" + head + r" \\" "\n" r"\midrule" "\n"
            + "\n".join(v2) + "\n" r"\bottomrule" "\n" r"\end{tabular}" "\n")
    write(SI / "sections" / "tab_tuned_v2.tex", "configs/tuned_v2.yaml", body)


# ---------------------------------------------------------------- capped versus uncapped runs

def capped_table(m: Macros) -> None:
    rows = []
    for rec, block, points in (("precision_a_b400_b654", "precision", ("400", "654")),
                               ("cv_extended_budget", "cv", ("10", "20"))):
        node = json.loads((ROOT / "results" / f"{rec}.json").read_text())["payload"]["descriptive"]["capped"]
        for pt in points:
            items = node[f"{block}|{pt}"]
            for bb in ("v2", "v1"):
                for model in ("S", "D"):
                    it = next(x for x in items if x["backbone"] == bb and x["model"] == model)
                    base = f"results/{rec}.json#/payload/descriptive/capped/{block}|{pt}/{bb}_{model}"
                    point = budget(m, pt) if block == "precision" else rf"$K = {m(f'{base}/point')}$"
                    design = "precision" if block == "precision" else "grouped CV"
                    cap = m(f"{base}/mean_single_run_mae_capped") if it.get("mean_single_run_mae_capped") is not None \
                        else "--"
                    unc = m(f"{base}/mean_single_run_mae_uncapped") \
                        if it.get("mean_single_run_mae_uncapped") is not None else "--"
                    rows.append(" & ".join([design, point if (bb, model) == ("v2", "S") else "", bb, model,
                                            m(f"{base}/n_runs"), m(f"{base}/n_capped"), cap, unc]) + r" \\")
            rows.append(r"\addlinespace")
    body = (r"\begin{tabular}{@{}llllrrrr@{}}" "\n" r"\toprule" "\n"
            r"Design & Budget or folds & Network & Model & Runs & Stopped at cap & MAE, capped & MAE, not capped \\"
            "\n" r"\midrule" "\n" + "\n".join(rows[:-1]) + "\n" r"\bottomrule" "\n" r"\end{tabular}" "\n")
    write(SI / "sections" / "tab_capped.tex",
          "results/precision_a_b400_b654.json, results/cv_extended_budget.json (payload.descriptive.capped)", body)


